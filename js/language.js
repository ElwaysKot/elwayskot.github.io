function setLanguage(lang) {
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (translations[lang] && translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  document.documentElement.lang = lang === "ua" ? "uk" : "ru";
  localStorage.setItem("siteLanguage", lang);
  
  document.querySelectorAll("input[data-placeholder-ru]").forEach(input => {
    input.placeholder =
      lang === "ua"
        ? input.dataset.placeholderUa
        : input.dataset.placeholderRu;
  });

  const languageToggle = document.getElementById("languageToggle");

  if (languageToggle) {
    languageToggle.textContent = lang === "ru" ? "RU" : "UA";
  }

  window.dispatchEvent(new Event("languageChanged"));
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLanguage = localStorage.getItem("siteLanguage") || "ru";
  const languageToggle = document.getElementById("languageToggle");

  setLanguage(savedLanguage);

  if (languageToggle) {
    languageToggle.addEventListener("click", () => {
      const currentLanguage = localStorage.getItem("siteLanguage") || "ru";
      const nextLanguage = currentLanguage === "ru" ? "ua" : "ru";

      setLanguage(nextLanguage);
    });
  }
});